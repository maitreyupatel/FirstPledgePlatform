const LATER_ADDITIONS = "960a 960b 960c 960d 306";

const VALID = new Set(`${CODEX_2015} ${LATER_ADDITIONS}`.split(/\s+/).filter(Boolean));

/** "150d", "472e", "330" — base number plus optional letter, lowercase. */
export function isKnownInsCode(code: string): boolean {
  return VALID.has(code.toLowerCase());
}
